#!/usr/bin/env python3
"""Regenerate requirements.lock from requirements.txt with per-file SHA-256 hashes.

Steps: resolve requirements.txt in a throwaway virtual environment, freeze
the exact versions, then fetch every published wheel/sdist digest for each
pinned version from the PyPI JSON API and write ``--hash=sha256:...``
entries. pip then runs in hash-checking mode on every platform
(``pip install --require-hashes`` is implied when hashes are present), so a
substituted wheel is refused by pip itself, before the wheelhouse
``SHA256SUMS`` check.

Extra arguments are passed to the throwaway ``pip install`` (for example
``"mcp==1.30.0"`` to hold a specific SDK release).
"""

from __future__ import annotations

import json
import subprocess
import sys
import tempfile
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
HEADER = (
    "# QECTOR Claude Plugin - exact runtime closure with per-file SHA-256 hashes.\n"
    "# Generated by scripts/update_lock.py from requirements.txt in a clean\n"
    "# virtual environment; digests fetched from the PyPI JSON API for every\n"
    "# published file of each pinned version, so pip verifies hashes on any\n"
    "# platform. Input of scripts/build_wheelhouse.py and of the air-gapped\n"
    "# installers. pip honours these hashes (hash-checking mode).\n"
)


def _digests(name: str, version: str) -> list[str]:
    with urllib.request.urlopen(f"https://pypi.org/pypi/{name}/{version}/json", timeout=30) as response:
        payload = json.loads(response.read().decode("utf-8"))
    digests = sorted({entry["digests"]["sha256"] for entry in payload["urls"] if not entry.get("yanked")})
    if not digests:
        raise SystemExit(f"no files published for {name}=={version}")
    return digests


def main() -> int:
    with tempfile.TemporaryDirectory() as tmp:
        venv = Path(tmp) / "venv"
        subprocess.run([sys.executable, "-m", "venv", str(venv)], check=True)
        python = venv / ("Scripts/python.exe" if sys.platform == "win32" else "bin/python")
        subprocess.run([str(python), "-m", "pip", "install", "-q", "-r", str(ROOT / "requirements.txt")] + sys.argv[1:], check=True)
        frozen = subprocess.run([str(python), "-m", "pip", "freeze", "--exclude-editable"], check=True, capture_output=True, text=True).stdout
    pins = sorted(line.strip() for line in frozen.splitlines() if "==" in line and not line.startswith("pip=="))
    blocks = []
    for pin in pins:
        name, version = pin.split("==", 1)
        hashes = _digests(name, version)
        blocks.append(pin + " \\\n" + " \\\n".join(f"    --hash=sha256:{digest}" for digest in hashes))
    (ROOT / "requirements.lock").write_text(HEADER + "\n".join(blocks) + "\n", encoding="utf-8")
    print(f"requirements.lock: {len(pins)} pinned distributions with hashes")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
